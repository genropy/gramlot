await embedded.inspector.open();
const dock = embedded.inspector.element;
assert.equal(dock.getAttribute('presentation'),'embedded');
assert.equal(dock.shadowRoot.querySelector('gnr-palette'),null);
assert.ok(dock.shadowRoot.querySelector('gnr-tabcontainer'));
assert.equal(dock.hidden,false);
assert.equal(dock.shadowRoot.querySelector('[data-inspector="data"]').storeBag,embedded.builder.data);
embedded.inspector.close();assert.equal(dock.hidden,true);
await embedded.inspector.open();assert.equal(dock.hidden,false);
assert.deepEqual(embeddedEvents,[true,false,true]);
