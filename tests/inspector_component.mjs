import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {setupDom} from '../js/dom/tests/dom.js';
setupDom();
const {Application, HtmlBuilder} = await import('gramlot-dom');
const {GramlotBuilder} = await import('../js/pages/src/builder.js');
const recipe = readFileSync(0, 'utf8');
let requests = 0;
globalThis.fetch = async url => { requests++; assert.match(String(url), /inspector.tytx$/); return {ok:true, text:async()=>recipe}; };
function page(options, Builder = GramlotBuilder) {
 const host = document.createElement('div'); document.body.append(host);
 class Example extends Builder { main(root) { root.div('Hello'); } }
 const builder = new Example('page');
 return new Application(host,builder,options);
}
const app = page();
assert.ok(app.inspector);
assert.equal(requests,0);
assert.equal(document.querySelector('gramlot-inspector'),null);
assert.equal(customElements.get('gramlot-inspector'),undefined);
const changes=[];
app.target.root.addEventListener('gramlot-inspector-change',e=>changes.push(e.detail.opened));
await app.inspector.open();
assert.equal(requests,1);
const component = app.inspector.element;
assert.equal(component.application,app);
assert.equal(component.tool.app.inspector,undefined,'internal application opts out');
assert.equal(component.shadowRoot.querySelector('[data-inspector="data"]').storeBag,app.builder.data);
assert.equal(component.shadowRoot.querySelector('[data-inspector="source"]').storeBag,app.builder.source);
assert.equal(app.inspector.opened,true);
assert.equal(changes.at(-1),true);
app.inspector.close();
assert.equal(changes.at(-1),false);
await app.inspector.open();
assert.equal(requests,1);
component.tool.app.live(()=>component.tool.app.builder.data.setItem('opened',false));
assert.equal(changes.at(-1),false,'palette close also announces state');
app.dispose();app.dispose();
assert.equal(component.tool.app._disposed,true);
assert.equal(document.querySelector('gramlot-inspector'),null);
const disabled=page({inspector:false});
assert.equal(disabled.inspector,undefined);
assert.equal(disabled.target.root.querySelector('button'),null);
disabled.dispose();
