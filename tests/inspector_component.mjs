await second.inspector.open();
assert.equal(first.inspector.element,null,'shortcut follows the application containing the event');
assert.equal(second.inspector.opened,true);
first.dispose();second.dispose();
globalThis.fetch = async url => {
 assert.match(String(url), /inspector-embedded.tytx$/);
 return {ok:true,text:async()=>process.env.INSPECTOR_EMBEDDED_SOURCE};
};
